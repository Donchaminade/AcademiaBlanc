CREATE TABLE etablissement (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(180) NOT NULL,
  code VARCHAR(40) NOT NULL,
  ville VARCHAR(120) NOT NULL,
  region VARCHAR(120),
  type_etablissement VARCHAR(160),
  email VARCHAR(180) NOT NULL,
  telephone VARCHAR(40),
  nom_responsable VARCHAR(180) NOT NULL
);

CREATE UNIQUE INDEX uk_etablissement_email ON etablissement (email);
CREATE UNIQUE INDEX uk_etablissement_code ON etablissement (code);

CREATE TABLE utilisateur (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  email VARCHAR(180) NOT NULL,
  mot_de_passe_hash VARCHAR(120) NOT NULL,
  nom VARCHAR(180) NOT NULL,
  role VARCHAR(30) NOT NULL
);

CREATE UNIQUE INDEX uk_utilisateur_email ON utilisateur (email);
CREATE INDEX idx_utilisateur_etablissement ON utilisateur (etablissement_id);

CREATE TABLE annee_scolaire (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  libelle VARCHAR(40) NOT NULL,
  date_debut DATE,
  date_fin DATE,
  courante BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_annee_etablissement ON annee_scolaire (etablissement_id);

CREATE TABLE centre_examen (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  nom VARCHAR(180) NOT NULL,
  ville VARCHAR(120),
  code VARCHAR(40) NOT NULL
);

CREATE INDEX idx_centre_etablissement ON centre_examen (etablissement_id);

CREATE TABLE session_examen (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  annee_scolaire_id BIGINT NOT NULL REFERENCES annee_scolaire (id),
  centre_id BIGINT NOT NULL REFERENCES centre_examen (id),
  nom VARCHAR(180) NOT NULL,
  type_examen VARCHAR(120) NOT NULL,
  serie VARCHAR(80),
  statut VARCHAR(40) NOT NULL
);

CREATE INDEX idx_session_etablissement ON session_examen (etablissement_id);

CREATE TABLE professeur (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  nom VARCHAR(180) NOT NULL,
  email VARCHAR(180),
  utilisateur_id BIGINT REFERENCES utilisateur (id)
);

CREATE INDEX idx_professeur_etablissement ON professeur (etablissement_id);

CREATE TABLE classe (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  annee_scolaire_id BIGINT NOT NULL REFERENCES annee_scolaire (id),
  nom VARCHAR(120) NOT NULL,
  niveau VARCHAR(80) NOT NULL,
  serie VARCHAR(80),
  titulaire_id BIGINT REFERENCES professeur (id)
);

CREATE INDEX idx_classe_etablissement ON classe (etablissement_id);

CREATE TABLE matiere (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  nom VARCHAR(180) NOT NULL,
  code VARCHAR(40) NOT NULL
);

CREATE UNIQUE INDEX uk_matiere_code_etab ON matiere (etablissement_id, code);

CREATE TABLE coefficient (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  matiere_id BIGINT NOT NULL REFERENCES matiere (id),
  classe_id BIGINT REFERENCES classe (id),
  serie VARCHAR(80),
  valeur NUMERIC(6, 2) NOT NULL
);

CREATE INDEX idx_coefficient_etablissement ON coefficient (etablissement_id);

CREATE TABLE affectation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  professeur_id BIGINT NOT NULL REFERENCES professeur (id),
  matiere_id BIGINT NOT NULL REFERENCES matiere (id),
  classe_id BIGINT NOT NULL REFERENCES classe (id)
);

CREATE UNIQUE INDEX uk_affectation ON affectation (professeur_id, matiere_id, classe_id);

CREATE TABLE eleve (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  classe_id BIGINT NOT NULL REFERENCES classe (id),
  session_id BIGINT REFERENCES session_examen (id),
  nom_complet VARCHAR(180) NOT NULL,
  matricule VARCHAR(60) NOT NULL,
  date_naissance VARCHAR(20),
  lieu_naissance VARCHAR(120),
  genre VARCHAR(1) NOT NULL,
  numero_table INTEGER,
  etablissement_origine VARCHAR(180)
);

CREATE UNIQUE INDEX uk_eleve_matricule_etab ON eleve (etablissement_id, matricule);
CREATE INDEX idx_eleve_etablissement ON eleve (etablissement_id);

CREATE TABLE note (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  eleve_id BIGINT NOT NULL REFERENCES eleve (id),
  matiere_id BIGINT NOT NULL REFERENCES matiere (id),
  session_id BIGINT NOT NULL REFERENCES session_examen (id),
  valeur NUMERIC(5, 2),
  absent BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT uk_note UNIQUE (eleve_id, matiere_id, session_id),
  CONSTRAINT ck_note_valeur CHECK (valeur IS NULL OR (valeur >= 0 AND valeur <= 20))
);

CREATE INDEX idx_note_etablissement ON note (etablissement_id);

CREATE TABLE bulletin (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  eleve_id BIGINT NOT NULL REFERENCES eleve (id),
  session_id BIGINT NOT NULL REFERENCES session_examen (id),
  moyenne NUMERIC(5, 2),
  rang INTEGER,
  mention VARCHAR(40),
  appreciation VARCHAR(40),
  total_points NUMERIC(8, 2),
  total_coef NUMERIC(8, 2),
  genere_le TIMESTAMP NOT NULL,
  CONSTRAINT uk_bulletin UNIQUE (eleve_id, session_id)
);
