-- Droits fins par utilisateur et gestionnaires de la plateforme.

-- Un gestionnaire de la plateforme n'appartient à aucun établissement.
ALTER TABLE utilisateur ALTER COLUMN etablissement_id DROP NOT NULL;

ALTER TABLE utilisateur ADD COLUMN actif BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE utilisateur ADD COLUMN cree_par BIGINT REFERENCES utilisateur (id);

-- Désactivation douce d'un établissement par la plateforme (aucune donnée n'est effacée).
ALTER TABLE etablissement ADD COLUMN actif BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE permission_utilisateur (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  utilisateur_id BIGINT NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
  ressource VARCHAR(40) NOT NULL,
  action VARCHAR(20) NOT NULL,
  accorde BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uk_permission_utilisateur UNIQUE (utilisateur_id, ressource, action)
);

CREATE INDEX idx_permission_utilisateur ON permission_utilisateur (utilisateur_id);
