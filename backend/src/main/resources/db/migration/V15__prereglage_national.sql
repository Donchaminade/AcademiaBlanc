-- Référentiel « pays / système éducatif » géré par la plateforme : république, devise nationale,
-- ministère de tutelle et son sigle, repris dans l'en-tête des bulletins. Remplace les deux
-- préréglages (Togo, Côte d'Ivoire) jusque-là codés en dur dans l'interface.
CREATE TABLE prereglage_national (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(2) NOT NULL,
  nom_pays VARCHAR(120) NOT NULL,
  republique VARCHAR(160) NOT NULL,
  devise VARCHAR(160) NOT NULL,
  ministere VARCHAR(240) NOT NULL,
  sigle_ministere VARCHAR(20) NOT NULL,
  autorite_regionale VARCHAR(160),
  pied_de_page VARCHAR(240),
  ordre INT NOT NULL DEFAULT 0,
  actif BOOLEAN NOT NULL DEFAULT TRUE,
  par_defaut BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE UNIQUE INDEX uk_prereglage_national_code ON prereglage_national (code);

