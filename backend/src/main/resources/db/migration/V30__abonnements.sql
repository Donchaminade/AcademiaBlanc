-- Historique : chaque essai, activation, prolongation, suspension, réactivation, déclaration de paiement
-- et expiration. `acteur` = email du compte à l'origine de l'action (super admin ou établissement).
-- `operateur_mobile` = Flooz, T-Money, Mixx by Yas… ; `statut` = A_VERIFIER / TRAITEE pour une déclaration.
CREATE TABLE evenement_abonnement (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  type VARCHAR(30) NOT NULL,
  forfait VARCHAR(20),
  montant BIGINT,
  reference VARCHAR(120),
  operateur_mobile VARCHAR(40),
  periode_debut TIMESTAMP WITH TIME ZONE,
  periode_fin TIMESTAMP WITH TIME ZONE,
  acteur VARCHAR(180),
  note VARCHAR(1000),
  statut VARCHAR(20),
  date_paiement TIMESTAMP WITH TIME ZONE,
  cree_le TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_evenement_abonnement_etab ON evenement_abonnement (etablissement_id, cree_le);
CREATE INDEX ix_evenement_abonnement_date ON evenement_abonnement (cree_le);

-- Établissements déjà inscrits avant ce déploiement : essai gratuit de 14 jours à partir de maintenant,
-- pour ne bloquer personne brutalement. Le super admin les active ensuite depuis le portail.
UPDATE etablissement
SET statut_abonnement = 'ESSAI',
    abonnement_debut = CURRENT_TIMESTAMP,
    abonnement_fin = CURRENT_TIMESTAMP + INTERVAL '14' DAY,
    abonnement_echeance = CURRENT_TIMESTAMP + INTERVAL '14' DAY,
    essai_jusqu_au = CURRENT_TIMESTAMP + INTERVAL '14' DAY;

INSERT INTO evenement_abonnement (etablissement_id, type, periode_debut, periode_fin, acteur, note, cree_le)
SELECT id, 'ESSAI', abonnement_debut, abonnement_fin, 'migration',
       'Essai de 14 jours accordé automatiquement aux établissements déjà inscrits (mise en place des abonnements).',
       CURRENT_TIMESTAMP
FROM etablissement;
