-- Abonnements et paiements manuels (mobile money, sans agrégateur).
--
-- État courant porté par l'établissement :
--   statut_abonnement : ESSAI | ACTIF | EXPIRE | EN_ATTENTE_PAIEMENT | SUSPENDU
--   forfait           : MENSUEL | ANNUEL (forfait de la période en cours, NULL en essai / attente)
--   forfait_choisi    : forfait retenu à l'inscription (proposé par défaut au super admin)
--   abonnement_debut  : début de la période courante (essai ou abonnement)
--   abonnement_fin    : fin de la période payée (ou fin d'essai)
--   abonnement_echeance : fin d'accès en écriture = fin + jours de grâce ; au-delà, lecture seule
--   essai_jusqu_au    : fin de l'essai gratuit (mémorisée même après activation)
-- Toutes les dates sont en UTC (timestamptz) ; les calculs sont faits par le serveur.
ALTER TABLE etablissement ADD COLUMN statut_abonnement VARCHAR(30) NOT NULL DEFAULT 'EN_ATTENTE_PAIEMENT';
ALTER TABLE etablissement ADD COLUMN forfait VARCHAR(20);
ALTER TABLE etablissement ADD COLUMN forfait_choisi VARCHAR(20);
ALTER TABLE etablissement ADD COLUMN abonnement_debut TIMESTAMP WITH TIME ZONE;
ALTER TABLE etablissement ADD COLUMN abonnement_fin TIMESTAMP WITH TIME ZONE;
ALTER TABLE etablissement ADD COLUMN abonnement_echeance TIMESTAMP WITH TIME ZONE;
ALTER TABLE etablissement ADD COLUMN essai_jusqu_au TIMESTAMP WITH TIME ZONE;

