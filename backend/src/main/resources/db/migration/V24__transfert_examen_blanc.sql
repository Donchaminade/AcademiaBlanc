-- Transfert des données d'un examen blanc commun entre établissements.
--
-- Chaque établissement détient un code de transfert personnel (8 caractères sans ambiguïté, « K7F3-9QZT »),
-- visible du seul chef d'établissement (OWNER / ADMIN). Le centre d'examen d'une session inter-établissements
-- envoie aux établissements d'origine de ses candidats un paquet figé (élèves, programme, notes, statistiques de
-- l'examen commun) en saisissant ce code ; le destinataire accepte ou refuse. L'acceptation crée chez lui une
-- session interne verrouillée (session_examen.transfert_source_id) et invalide le code utilisé (un nouveau est
-- généré). Les codes manquants (établissements antérieurs) sont générés au démarrage de l'application.
ALTER TABLE etablissement ADD COLUMN code_transfert VARCHAR(20);
CREATE UNIQUE INDEX uk_etablissement_code_transfert ON etablissement (code_transfert);

ALTER TABLE session_examen ADD COLUMN transfert_source_id BIGINT;

CREATE TABLE transfert_examen (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_source_id BIGINT NOT NULL REFERENCES etablissement (id),
  -- La session du centre peut être supprimée plus tard : l'historique des envois reste lisible.
  session_source_id BIGINT REFERENCES session_examen (id) ON DELETE SET NULL,
  etablissement_origine VARCHAR(180) NOT NULL,
  etablissement_destination_id BIGINT NOT NULL REFERENCES etablissement (id),
  code_utilise VARCHAR(20) NOT NULL,
  statut VARCHAR(20) NOT NULL,
  envoye_le TIMESTAMP NOT NULL,
  envoye_par BIGINT REFERENCES utilisateur (id),
  traite_le TIMESTAMP,
  traite_par BIGINT REFERENCES utilisateur (id),
  motif_refus VARCHAR(500),
  session_creee_id BIGINT REFERENCES session_examen (id) ON DELETE SET NULL,
  effectif INTEGER NOT NULL DEFAULT 0,
  type_examen VARCHAR(120),
  session_nom VARCHAR(180) NOT NULL,
  annee_libelle VARCHAR(40),
  -- Instantané JSON du paquet au moment de l'envoi (TEXT : porté à l'identique par PostgreSQL et H2).
  paquet TEXT NOT NULL
);
CREATE INDEX ix_transfert_source ON transfert_examen (etablissement_source_id, session_source_id);
CREATE INDEX ix_transfert_destination ON transfert_examen (etablissement_destination_id, statut);

-- Statistiques de l'examen commun conservées chez le destinataire pour chaque élève importé : le bulletin
-- affiche le rang et les extrêmes du groupe de classement complet de la session du centre, pas ceux
-- recalculés sur les seuls élèves de l'établissement. lignes : JSON [{matiereId, rang, noteMax, noteMin, effectif}].
CREATE TABLE transfert_stat_eleve (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  transfert_id BIGINT NOT NULL REFERENCES transfert_examen (id),
  session_id BIGINT NOT NULL REFERENCES session_examen (id) ON DELETE CASCADE,
  eleve_id BIGINT NOT NULL REFERENCES eleve (id) ON DELETE CASCADE,
  moyenne NUMERIC(5, 2),
  rang INTEGER,
  effectif_groupe INTEGER,
  moyenne_groupe NUMERIC(5, 2),
  moyenne_max_groupe NUMERIC(5, 2),
  moyenne_min_groupe NUMERIC(5, 2),
  mention VARCHAR(40),
  decision VARCHAR(20),
  lignes TEXT,
  CONSTRAINT uk_transfert_stat_eleve UNIQUE (session_id, eleve_id)
);
