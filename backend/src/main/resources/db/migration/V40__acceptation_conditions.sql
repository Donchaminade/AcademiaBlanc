-- Preuve d'acceptation des documents légaux (CGU, conditions d'utilisation, politique de confidentialité).
-- Une ligne est écrite à l'inscription, dans la même transaction que la création du compte, puis une
-- nouvelle ligne à chaque ré-acceptation quand la version des conditions change (jamais de mise à jour :
-- l'historique complet est conservé). accepte_le est l'instant UTC du serveur, jamais celui du navigateur.
CREATE TABLE acceptation_conditions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  utilisateur_id BIGINT NOT NULL REFERENCES utilisateur (id),
  email VARCHAR(180) NOT NULL,
  version_conditions VARCHAR(40) NOT NULL,
  accepte_le TIMESTAMP WITH TIME ZONE NOT NULL,
  adresse_ip VARCHAR(64),
  user_agent VARCHAR(255)
);

CREATE INDEX idx_acceptation_conditions_etablissement ON acceptation_conditions (etablissement_id, accepte_le DESC);
