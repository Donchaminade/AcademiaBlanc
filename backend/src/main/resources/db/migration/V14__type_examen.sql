-- Référentiel des types d'examen, commun à toute la plateforme (géré par le propriétaire du logiciel).
-- Chaque session d'examen d'un établissement choisit l'un de ces types ; session_examen.type_examen
-- (texte) reste le libellé court, synchronisé par l'API, pour les bulletins et archives existants.
CREATE TABLE type_examen (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(20) NOT NULL,
  libelle_court VARCHAR(60) NOT NULL,
  libelle_long VARCHAR(160) NOT NULL,
  cycle VARCHAR(20) NOT NULL,
  ordre INTEGER NOT NULL DEFAULT 0,
  actif BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT ck_type_examen_cycle CHECK (cycle IN ('COLLEGE', 'LYCEE', 'TOUS'))
);

CREATE UNIQUE INDEX uk_type_examen_code ON type_examen (code);

