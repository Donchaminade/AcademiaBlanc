-- Rattachement des sessions : colonne nullable pour une migration douce.
ALTER TABLE session_examen ADD COLUMN type_examen_id BIGINT REFERENCES type_examen (id);
CREATE INDEX idx_session_type_examen ON session_examen (type_examen_id);

-- Sessions existantes : rattachées d'après leur libellé texte, du plus précis au plus général.
UPDATE session_examen SET type_examen_id = (SELECT id FROM type_examen WHERE code = 'BEPC')
  WHERE type_examen_id IS NULL AND UPPER(type_examen) LIKE '%BEPC%';
UPDATE session_examen SET type_examen_id = (SELECT id FROM type_examen WHERE code = 'CEPD')
  WHERE type_examen_id IS NULL AND UPPER(type_examen) LIKE '%CEPD%';
UPDATE session_examen SET type_examen_id = (SELECT id FROM type_examen WHERE code = 'BAC1')
  WHERE type_examen_id IS NULL AND (
    UPPER(type_examen) LIKE '%BAC% I' OR UPPER(type_examen) LIKE '%BAC% I %' OR UPPER(type_examen) LIKE '%BAC% 1%'
    OR UPPER(type_examen) LIKE '%PREMI_RE PARTIE%' OR UPPER(type_examen) LIKE '%PROBATOIRE%');
-- Avant cette version, le type était figé à « BACCALAURÉAT II » : tout libellé « BAC » restant va au BAC II.
UPDATE session_examen SET type_examen_id = (SELECT id FROM type_examen WHERE code = 'BAC2')
  WHERE type_examen_id IS NULL AND UPPER(type_examen) LIKE '%BAC%';
UPDATE session_examen SET type_examen_id = (SELECT id FROM type_examen WHERE code = 'COMPO')
  WHERE type_examen_id IS NULL AND (UPPER(type_examen) LIKE '%COMPO%' OR UPPER(type_examen) LIKE '%BLANC INTERNE%');

-- Le texte reprend le libellé court du référentiel pour les sessions rattachées.
UPDATE session_examen SET type_examen = (SELECT libelle_court FROM type_examen WHERE type_examen.id = session_examen.type_examen_id)
  WHERE type_examen_id IS NOT NULL;
