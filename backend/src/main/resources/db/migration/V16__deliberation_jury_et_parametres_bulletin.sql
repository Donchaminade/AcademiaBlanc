-- Délibération du jury par élève et par session : bonus de repêchage, observation portée sur le
-- bulletin et signature électronique apposée depuis l'application. Table distincte de `bulletin`,
-- dont les lignes sont recalculées et écrasées à chaque génération : une décision du jury doit
-- survivre à ces recalculs et exister même si aucun bulletin n'a encore été généré.
CREATE TABLE deliberation_jury (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id BIGINT NOT NULL REFERENCES etablissement (id),
  eleve_id BIGINT NOT NULL REFERENCES eleve (id) ON DELETE CASCADE,
  session_id BIGINT NOT NULL REFERENCES session_examen (id),
  bonus_jury NUMERIC(4, 2) NOT NULL DEFAULT 0,
  observation TEXT,
  signe_le TIMESTAMP,
  signataire VARCHAR(180),
  empreinte_signature VARCHAR(128),
  modifie_le TIMESTAMP NOT NULL,
  CONSTRAINT uk_deliberation_jury UNIQUE (eleve_id, session_id)
);
CREATE INDEX idx_deliberation_jury_session ON deliberation_jury (etablissement_id, session_id);

-- Paramètres d'affichage du bulletin propres à l'établissement (écran Paramètres) : logo, sceau
-- officiel, signataires et numérotation des tables. Jusqu'ici conservés dans le navigateur, donc perdus
-- d'un poste à l'autre. NULL = valeur par défaut du logiciel. L'en-tête officiel (république, devise,
-- ministère) est porté par `etablissement` (préréglages nationaux, V15) et n'est pas dupliqué ici.
CREATE TABLE parametres_bulletin (
  etablissement_id BIGINT PRIMARY KEY REFERENCES etablissement (id),
  logo_url TEXT,
  sceau_officiel_url TEXT,
  titre_signataire_jury VARCHAR(120),
  nom_signataire_jury VARCHAR(180),
  titre_titulaire VARCHAR(120),
  nom_titulaire VARCHAR(180),
  premier_numero_table INTEGER,
  numerotation_automatique BOOLEAN,
  modifie_le TIMESTAMP NOT NULL
);
